const { data: vendors, error } = await supabase
  .from("vendors")
  .select("id, name, address, description");
if (error) throw error;

let updated = 0;
for (const v of vendors) {
  const areaT = v.address ? AREAS[v.address] : undefined;
  const descT = DESCRIPTIONS[v.name];
  const nameT = NAMES[v.name];
  if (!areaT && !descT && !nameT) continue;

  const translations = {
    en: { name: nameT?.en },
    fa: { address: areaT?.fa, description: descT?.fa },
    ar: { name: nameT?.ar, address: areaT?.ar, description: descT?.ar },
  };

  const { error: updateError } = await supabase
    .from("vendors")
    .update({ translations })
    .eq("id", v.id);
  if (updateError) {
    console.error(`Failed for ${v.name}:`, updateError.message);
    continue;
  }
  updated++;
}

console.log(`Localized ${updated} of ${vendors.length} vendors.`);
